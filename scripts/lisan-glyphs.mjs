// Regenerates lib/lisan.ts: the receipt's fixed Lisan ud-Dawat labels as PDF vector paths, already shaped
// (joined letter forms, right-to-left), so the runtime PDF writer needs no font file or shaping library.
// Run after changing a phrase:  node scripts/lisan-glyphs.mjs <path to NotoNaskhArabic[wght].ttf>
// Font: https://github.com/google/fonts/tree/main/ofl/notonaskharabic (SIL Open Font License)
import fs from "node:fs";
import * as fontkit from "fontkit";

const PHRASES = {
  date: "تاريخ :",
  receiptNo: "رسيد نمبر :",
  name: "نام :",
  honorific: "حفظه الله تعالى",
  fromYou: "آپ طرف سي",
  amount: "انكه",
  greeting: "بعد السلام الجميل",
  received: "وصول كرنار ني صحيح",
};

const font = fontkit.openSync(process.argv[2]);
const k = 1000 / font.unitsPerEm; // store in 1/1000 em, like PDF text space
const n = (v) => Math.round(v * k * 10) / 10;

const out = {};
for (const [key, text] of Object.entries(PHRASES)) {
  const run = font.layout(text); // fontkit shapes Arabic and returns glyphs in visual (left-to-right) order
  let x = 0;
  const ops = [];
  run.glyphs.forEach((g, i) => {
    const p = run.positions[i];
    const ox = x + p.xOffset, oy = p.yOffset;
    let cx = 0, cy = 0; // current point, for quadratic → cubic conversion
    for (const { command, args } of g.path.commands) {
      if (command === "moveTo" || command === "lineTo") {
        [cx, cy] = args;
        ops.push(`${n(ox + cx)} ${n(oy + cy)} ${command === "moveTo" ? "m" : "l"}`);
      } else if (command === "quadraticCurveTo") {
        const [qx, qy, x2, y2] = args;
        const c1 = [cx + (2 / 3) * (qx - cx), cy + (2 / 3) * (qy - cy)], c2 = [x2 + (2 / 3) * (qx - x2), y2 + (2 / 3) * (qy - y2)];
        ops.push(`${n(ox + c1[0])} ${n(oy + c1[1])} ${n(ox + c2[0])} ${n(oy + c2[1])} ${n(ox + x2)} ${n(oy + y2)} c`);
        [cx, cy] = [x2, y2];
      } else if (command === "bezierCurveTo") {
        const [a, b, c, d, x2, y2] = args;
        ops.push(`${n(ox + a)} ${n(oy + b)} ${n(ox + c)} ${n(oy + d)} ${n(ox + x2)} ${n(oy + y2)} c`);
        [cx, cy] = [x2, y2];
      } else if (command === "closePath") ops.push("h");
    }
    x += p.xAdvance;
  });
  out[key] = { w: n(x), d: ops.join(" ") };
}

fs.writeFileSync(
  new URL("../lib/lisan.ts", import.meta.url),
  `// Generated by scripts/lisan-glyphs.mjs from Noto Naskh Arabic (SIL OFL). Do not edit by hand.\n` +
    `// Each phrase: w = width and d = PDF path ops, both in 1/1000 em, origin at the baseline's left end.\n` +
    `export const LISAN = ${JSON.stringify(out, null, 1)} as const;\n`,
);
console.log(Object.fromEntries(Object.entries(out).map(([key, v]) => [key, `${v.w} wide, ${v.d.length} chars`])));
